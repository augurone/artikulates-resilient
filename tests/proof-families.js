const familyPrefixes = Object.freeze({
    transformer: ['typescript-', 'tuple-return-'],
    operations: ['artifact-', 'proof-', 'inspection-', 'project-adapter', 'project-measurement-', 'module-resolution-',
        'benchmark-', 'integration-', 'eslint-exception-', 'project-dogfood-', 'documentation-', 'catalog-'],
    analyzer: ['analyzer-', 'contracts-', 'contract.', 'document-', 'program-', 'project-', 'variant-', 'flow-', 'graph-', 'bounded-'],
    rules: ['no-', 'prefer-', 'signature-', 'rule-', 'recommended-', 'safety-', 'imports-', 'plugin-'],
    standard: ['array-', 'function-', 'object-', 'value-']
});
const selectProofs = (args = []) => {
    if (!args.length) return testFiles;

    const [flag = '', family = '', ...rest] = args;
    const { [family]: prefixes = [] } = familyPrefixes;

    if (flag !== '--family' || !prefixes.length || rest.length) {
        throw new Error(`Usage: npm test -- --family <${Object.keys(familyPrefixes).join('|')}>`);
    }

    return testFiles.filter(file => prefixes.some(prefix => file.startsWith(`./${prefix}`)));
};

export { testFiles, familyPrefixes, selectProofs };
